inline int16_t sin88(uint8_t angle) {
    return g_sine_table[angle];
}

inline int16_t cos88(uint8_t angle) {
    return g_sine_table[(angle + 64) & 0xFF];
}

// Fixed-radius (90) offsets for the player, avoiding a runtime multiply.
inline int16_t player_offset_x(uint8_t angle) {
    return g_player_offset[angle];
}

inline int16_t player_offset_y(uint8_t angle) {
    return g_player_offset[(angle + 64) & 0xFF];
}

static inline int16_t ghost_offset_x(uint8_t angle) {
    return g_ghost_offset[angle];
}

static inline int16_t ghost_offset_y(uint8_t angle) {
    return g_ghost_offset[(uint8_t)(angle + 64)];
}

// Replaces (value * 128) / z; caller must ensure z != 0.
inline int16_t div128(int16_t value, uint8_t z) {
    return ((int32_t)value * g_recip128_table[z]) >> 8;
}

